"""Small synthetic training tasks and parameter-held-out evaluation tasks.

These are two shared bug templates, not an unseen-repository coding benchmark.
Teacher actions are exported only for the training partition's SFT warmup.
"""
from __future__ import annotations

import json
from pathlib import Path
import subprocess
import sys
import tempfile

from ..schema import Task
from .rollout import initial_messages, observation


TEST_COMMAND = ["python", "-m", "unittest", "discover", "-s", "tests", "-v"]


def _tests(function: str, cases: list[tuple], prefix: str) -> str:
    methods = []
    for i, (argument, expected) in enumerate(cases):
        methods.append(f"    def test_{prefix}_{i}(self):\n"
                       f"        self.assertEqual({function}({argument!r}), {expected!r})\n")
    return ("import unittest\nfrom solution import " + function + "\n\n\n"
            "class Tests(unittest.TestCase):\n" + "\n".join(methods))


def _problem(family: str, value: int) -> tuple[str, str, str, str, str]:
    if family == "threshold":
        issue = (f"In solution.py, qualifies(value) must return True when value is at least {value}, "
                 "including the boundary, and False below it. Fix the boundary bug.")
        broken = f"def qualifies(value):\n    return value > {value}\n"
        fixed = f"def qualifies(value):\n    return value >= {value}\n"
        public_cases = [(value - 1, False), (value, True), (value + 1, True)]
        private_cases = [(value - 100, False), (value - 0.25, False), (value, True),
                         (value + 0.25, True), (value + 100, True)]
        function = "qualifies"
    else:
        issue = (f"In solution.py, collect(start) must list all integers from start through {value} "
                 f"inclusive, or [] when start exceeds {value}. Fix the missing upper endpoint.")
        broken = f"def collect(start):\n    return list(range(start, {value}))\n"
        fixed = f"def collect(start):\n    return list(range(start, {value + 1}))\n"
        public_cases = [(value - 2, [value - 2, value - 1, value]), (value, [value]), (value + 1, [])]
        private_cases = [(value - 5, list(range(value - 5, value + 1))),
                         (value - 1, [value - 1, value]), (value, [value]),
                         (value + 2, []), (value + 20, [])]
        function = "collect"
    return issue, broken, fixed, _tests(function, public_cases, "public"), _tests(function, private_cases, "hidden")


def _demonstration(task: Task, broken: str, fixed: str, public_tests: str) -> dict:
    # Teacher code is generated by this module, never sampled from a model.
    with tempfile.TemporaryDirectory(prefix="budget-agent-teacher-") as directory:
        repo = Path(directory)
        (repo / "solution.py").write_text(fixed, encoding="utf-8")
        (repo / "tests").mkdir()
        (repo / "tests/test_public.py").write_text(public_tests, encoding="utf-8")
        result = subprocess.run([sys.executable, *TEST_COMMAND[1:]], cwd=repo,
                                text=True, encoding="utf-8", stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT, check=True)
    actions = [
        {"tool": "read_file", "path": "solution.py"},
        {"tool": "write_file", "path": "solution.py", "content": fixed},
        {"tool": "run", "command": " ".join(TEST_COMMAND)},
        {"tool": "finish"},
    ]
    outputs = ["\n".join(f"{i + 1}: {line}" for i, line in enumerate(broken.splitlines())),
               "Wrote solution.py", result.stdout]
    messages = initial_messages(task)
    for i, action in enumerate(actions):
        messages.append({"role": "assistant", "content": json.dumps(action)})
        if i < len(outputs):
            messages.append(observation({"ok": True, "output": outputs[i]}))
    return {"task_id": task.id, "split": "train", "messages": messages}


def generate_curriculum(output_dir: Path, train_count: int = 12, eval_count: int = 6) -> dict[str, Path]:
    """Write disjoint task manifests; increasing a split does not alter the other."""
    if train_count < 1 or eval_count < 1:
        raise ValueError("Both curriculum partitions need at least one task")
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = {name: output_dir / f"{name}.jsonl" for name in ("train", "eval", "sft")}
    demos = []
    for split, count in (("train", train_count), ("eval", eval_count)):
        rows = []
        for index in range(count):
            family = ("threshold", "range")[index % 2]
            # Odd training and even evaluation constants remain disjoint at every size.
            value = 2 * (index // 2) + (1 if split == "train" else 2)
            issue, broken, fixed, public, private = _problem(family, value)
            task_id = f"{split}-{family}-{value}"
            directory = output_dir / "fixtures" / task_id
            repo = directory / "repo"
            (repo / "tests").mkdir(parents=True, exist_ok=True)
            (repo / "solution.py").write_text(broken, encoding="utf-8")
            (repo / "tests/test_public.py").write_text(public, encoding="utf-8")
            (directory / "verify.py").write_text(private, encoding="utf-8")
            task = Task(id=task_id, issue=issue, split=split, kind="local",
                        repo=repo.relative_to(output_dir).as_posix(), test_command=TEST_COMMAND,
                        verifier=(directory / "verify.py").relative_to(output_dir).as_posix(),
                        metadata={"suite": "synthetic-curriculum-v2", "family": family,
                                  "parameter": value, "editable": ["solution.py"],
                                  "holdout": "parameters; shared bug templates"})
            rows.append(task.__dict__)
            if split == "train":
                demos.append(_demonstration(task, broken, fixed, public))
        paths[split].write_text("".join(json.dumps(row) + "\n" for row in rows), encoding="utf-8")
    paths["sft"].write_text("".join(json.dumps(row) + "\n" for row in demos), encoding="utf-8")
    return paths
