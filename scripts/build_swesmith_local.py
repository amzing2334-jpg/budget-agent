"""Build Docker-free SWE-smith tasks with admission checks.

For each selected instance (see the SWE-smith dataset), this script:
  1. creates one virtualenv per repository (dependencies and dist metadata
     from a non-editable install; the code under test always comes from the
     tree being tested, which every test run asserts),
  2. runs the instance's FAIL_TO_PASS/PASS_TO_PASS files on the clean tree
     twice and on the bug-applied tree once,
  3. admits the instance only if every FAIL_TO_PASS test passes on both clean
     runs, at least one fails with the bug, outcomes repeat exactly, and the
     package imports from the tree under test,
  4. writes a budget-agent task manifest: the bug-applied repository is the
     starting state and a private verifier re-runs the admitted tests.

Pass-to-pass tests that do not pass on clean and bug trees in this
environment are dropped and counted. The script only uses the standard
library so it can run with the host interpreter.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import json
import math
import os
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import sys
import tempfile
import time

PLUGIN_MODULE = "budget_agent_pytest_outcomes"
PROTECTED_NAMES = {"conftest.py", "setup.py", "noxfile.py", "tasks.py"}

VERIFIER = '''"""Private verifier for {instance_id}. Generated by build_swesmith_local.py."""
import json
import os
import subprocess
import tempfile
import unittest

SPEC = json.loads({spec!r})


def _environment(tree, outcomes=None):
    env = {{"PATH": os.path.dirname(SPEC["python"]) + os.pathsep + "/usr/local/bin:/usr/bin:/bin",
           "PYTHONPATH": os.pathsep.join([os.path.join(tree, "src"), tree, SPEC["plugin_dir"]]),
           "PYTHONDONTWRITEBYTECODE": "1", "PYTHONHASHSEED": "0", "HOME": tempfile.gettempdir(),
           "LANG": "C.UTF-8", "LC_ALL": "C.UTF-8"}}
    if outcomes:
        env["BUDGET_AGENT_OUTCOMES"] = outcomes
    return env


class HiddenTests(unittest.TestCase):
    def test_admitted_tests_pass_from_this_tree(self):
        tree = os.path.realpath(os.getcwd())
        origin = subprocess.run([SPEC["python"], "-c", "import {{0}}; print({{0}}.__file__)".format(SPEC["import_name"])],
                                cwd=tree, env=_environment(tree), capture_output=True, text=True, timeout=120)
        path = os.path.realpath(origin.stdout.strip() or "/nonexistent")
        self.assertTrue(path.startswith(tree + os.sep), "code under test imported from " + path + origin.stderr[-500:])
        with tempfile.TemporaryDirectory() as scratch:
            outcomes = os.path.join(scratch, "outcomes.json")
            subprocess.run([SPEC["python"], "-m", "pytest", "-p", SPEC["plugin"], "-p", "no:cacheprovider",
                            "-q", "--tb=no", "--color=no", *SPEC["files"]],
                           cwd=tree, env=_environment(tree, outcomes), capture_output=True, text=True,
                           timeout=SPEC["timeout"])
            with open(outcomes, encoding="utf-8") as stream:
                observed = json.load(stream)["outcomes"]
        failing = sorted(t for t in SPEC["fail_to_pass"] + SPEC["pass_to_pass"] if observed.get(t) != "passed")
        self.assertEqual(failing, [], "admitted tests not passing")


if __name__ == "__main__":
    unittest.main()
'''


def run(command, cwd, env=None, timeout=900, check=True):
    if env is None:
        # SWE-smith mirrors are shallow snapshots without tags; setuptools_scm
        # packages (e.g. tenacity) cannot infer a version from them.
        env = {**os.environ, "SETUPTOOLS_SCM_PRETEND_VERSION": os.environ.get("SETUPTOOLS_SCM_PRETEND_VERSION", "0.0.0")}
    result = subprocess.run(command, cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout)
    if check and result.returncode != 0:
        raise RuntimeError(f"{' '.join(map(str, command))} failed ({result.returncode}): {result.stdout[-2000:]}{result.stderr[-2000:]}")
    return result


def test_environment(tree: Path, venv: Path, plugin_dir: Path, outcomes: Path | None = None) -> dict:
    env = {"PATH": f"{venv / 'bin'}{os.pathsep}/usr/local/bin:/usr/bin:/bin",
           "PYTHONPATH": os.pathsep.join([str(tree / "src"), str(tree), str(plugin_dir)]),
           "PYTHONDONTWRITEBYTECODE": "1", "PYTHONHASHSEED": "0", "HOME": tempfile.gettempdir(),
           "LANG": "C.UTF-8", "LC_ALL": "C.UTF-8"}
    if outcomes is not None:
        env["BUDGET_AGENT_OUTCOMES"] = str(outcomes)
    return env


def prepare_venv(name: str, clean: Path, venv: Path, python: str, extras: list[str]) -> dict:
    started = time.monotonic()
    if not (venv / "bin" / "python").exists():
        run([python, "-m", "venv", str(venv)], cwd=clean)
        interpreter = str(venv / "bin" / "python")
        pip = [interpreter, "-m", "pip", "install", "-q", "--disable-pip-version-check"]
        run([*pip, "pytest", "pytest-cov", *extras], cwd=clean)
        # SWE-smith images ran `pip install -e .` inside the checkout, which writes
        # build-time sources (e.g. a setuptools_scm version.py) into the tree.
        # Reproduce those files in the clean clone, then drop the editable link.
        run([*pip, "-e", str(clean)], cwd=clean)
        linked = json.loads(run([interpreter, "-m", "pip", "list", "--editable", "--format=json",
                                 "--disable-pip-version-check"], cwd=clean).stdout)
        run([interpreter, "-m", "pip", "uninstall", "-y", "-q", *[d["name"] for d in linked]], cwd=clean)
        # Non-editable: an editable install points at this clone, not at the tree under test.
        with tempfile.TemporaryDirectory() as build:
            copy = Path(build) / clean.name
            shutil.copytree(clean, copy, ignore=shutil.ignore_patterns(".git"))
            run([*pip, str(copy)], cwd=build)
    version = run([str(venv / "bin" / "python"), "-c", "import sys; print(sys.version.split()[0])"], cwd=clean).stdout.strip()
    return {"repo": name, "python": version, "seconds": round(time.monotonic() - started, 1)}


def import_name(patch_path: str, tree: Path) -> str:
    parts = PurePosixPath(patch_path).parts
    if parts[0] == "src":
        parts = parts[1:]
    if len(parts) == 1:
        return PurePosixPath(parts[0]).stem
    return parts[0]


def run_tests(tree: Path, venv: Path, plugin_dir: Path, files: list[str], name: str, timeout: int) -> dict:
    origin = run([str(venv / "bin" / "python"), "-c", f"import {name}; print({name}.__file__)"],
                 cwd=tree, env=test_environment(tree, venv, plugin_dir), timeout=120, check=False)
    location = os.path.realpath(origin.stdout.strip() or "/nonexistent")
    with tempfile.TemporaryDirectory() as scratch:
        outcomes = Path(scratch) / "outcomes.json"
        started = time.monotonic()
        proc = run([str(venv / "bin" / "python"), "-m", "pytest", "-p", PLUGIN_MODULE, "-p", "no:cacheprovider",
                    "-q", "--tb=no", "--color=no", *files], cwd=tree,
                   env=test_environment(tree, venv, plugin_dir, outcomes), timeout=timeout, check=False)
        seconds = time.monotonic() - started
        observed = json.loads(outcomes.read_text())["outcomes"] if outcomes.exists() else {}
    return {"origin_ok": location.startswith(os.path.realpath(tree) + os.sep), "origin": location,
            "outcomes": observed, "exit": proc.returncode, "seconds": seconds,
            "tail": (proc.stdout + proc.stderr)[-1500:]}


def copy_tree(source: Path, destination: Path) -> None:
    shutil.copytree(source, destination, symlinks=True, ignore=shutil.ignore_patterns(".git"))
    for path in list(destination.rglob("*")):
        if path.is_symlink():  # the harness rejects symlinks in task repositories
            path.unlink()


def verifier_timeout_seconds(seconds: dict[str, float]) -> int:
    """Grading time limit from the admission runs: 10x the slowest, at least 30 s.

    A uniform limit (300 s in round 1) let one hung candidate hold a whole
    synchronous rollout batch for minutes; admitted suites take 0.5 s at
    the median.
    """
    return max(30, math.ceil(10 * max(seconds.values())))


def admit(instance: dict, clean: Path, venv: Path, plugin_dir: Path, output: Path, timeout: int) -> dict:
    instance_id = instance["instance_id"]
    f2p, p2p = instance["FAIL_TO_PASS"], instance["PASS_TO_PASS"]
    files = sorted({test.split("::")[0] for test in f2p + p2p})
    patch_files = [line[len("+++ b/"):] for line in instance["patch"].splitlines() if line.startswith("+++ b/")]
    name = import_name(patch_files[0], clean)
    record = {"instance_id": instance_id, "repo": instance["repo"], "split": instance["split"],
              "admitted": False, "import_name": name}
    with tempfile.TemporaryDirectory() as scratch:
        gold, bug = Path(scratch) / "gold", Path(scratch) / "bug"
        copy_tree(clean, gold)
        copy_tree(clean, bug)
        patch = Path(scratch) / "bug.patch"
        patch.write_text(instance["patch"], encoding="utf-8")
        applied = run(["git", "apply", "--whitespace=nowarn", str(patch)], cwd=bug, check=False)
        if applied.returncode != 0:
            return {**record, "reason": "patch does not apply", "detail": applied.stderr[-500:]}
        g1 = run_tests(gold, venv, plugin_dir, files, name, timeout)
        g2 = run_tests(gold, venv, plugin_dir, files, name, timeout)
        b = run_tests(bug, venv, plugin_dir, files, name, timeout)
        record["seconds"] = {"gold": round(g1["seconds"], 2), "bug": round(b["seconds"], 2)}
        if not (g1["origin_ok"] and g2["origin_ok"] and b["origin_ok"]):
            return {**record, "reason": "code under test imported from outside the tree", "origin": g1["origin"]}
        if any(g1["outcomes"].get(t) != "passed" for t in f2p):
            missing = [t for t in f2p if g1["outcomes"].get(t) != "passed"][:3]
            return {**record, "reason": "FAIL_TO_PASS not passing on clean tree", "examples": missing, "tail": g1["tail"]}
        f2p_eff = [t for t in f2p if b["outcomes"].get(t) != "passed"]
        if not f2p_eff:
            return {**record, "reason": "bug does not break any FAIL_TO_PASS test here"}
        p2p_eff = [t for t in p2p if g1["outcomes"].get(t) == "passed" and b["outcomes"].get(t) == "passed"]
        watched = f2p_eff + p2p_eff
        if any(g1["outcomes"].get(t) != g2["outcomes"].get(t) for t in watched):
            return {**record, "reason": "flaky on clean tree"}
        if len(p2p) and len(p2p_eff) < 0.8 * len(p2p):
            return {**record, "reason": "environment drops over 20% of PASS_TO_PASS",
                    "p2p_kept": len(p2p_eff), "p2p_total": len(p2p)}
        task_dir = output / "tasks" / instance_id
        if task_dir.exists():
            shutil.rmtree(task_dir)
        copy_tree(bug, task_dir / "repo")
        editable = sorted(p.relative_to(task_dir / "repo").as_posix() for p in (task_dir / "repo").rglob("*.py")
                          if p.is_file() and not _protected(p.relative_to(task_dir / "repo").as_posix()))
        spec = {"python": str(venv / "bin" / "python"), "plugin_dir": str(plugin_dir), "plugin": PLUGIN_MODULE,
                "import_name": name, "files": files, "fail_to_pass": f2p_eff, "pass_to_pass": p2p_eff,
                "timeout": timeout}
        (task_dir / "verify.py").write_text(VERIFIER.format(instance_id=instance_id, spec=json.dumps(spec)), encoding="utf-8")
        task = {"id": instance_id, "issue": instance["problem_statement"].strip(), "split": instance["split"],
                "kind": "local", "repo": f"tasks/{instance_id}/repo", "verifier": f"tasks/{instance_id}/verify.py",
                "test_command": ["python", "-m", "pytest", "-q", "-p", "no:cacheprovider", "--tb=short", *files],
                "metadata": {"suite": "swesmith-local-v1", "instance_id": instance_id, "source_repo": instance["repo"],
                             "editable": editable, "grading_scope": "editable_only",
                             # SWE-smith bugs live in public repos: block fetching the pristine upstream file.
                             "network_policy": "deny",
                             "exec_env": {"PATH": str(venv / "bin"), "PYTHONPATH": "{workspace}/src:{workspace}",
                                          # pytest-cov (repo addopts) writes outside the graded tree
                                          "COVERAGE_FILE": "{workspace}.coverage"},
                             "fail_to_pass": len(f2p_eff), "pass_to_pass": len(p2p_eff),
                             "pass_to_pass_dropped": len(p2p) - len(p2p_eff),
                             "verifier_timeout_seconds": verifier_timeout_seconds(record["seconds"])}}
        return {**record, "admitted": True, "task": task, "f2p_eff": len(f2p_eff), "f2p_total": len(f2p),
                "p2p_eff": len(p2p_eff), "p2p_total": len(p2p)}


def _protected(relative: str) -> bool:
    path = PurePosixPath(relative)
    return (any(part in {"tests", "test", "testing", ".git"} for part in path.parts)
            or path.name.startswith(("test_", "_private_")) or path.name.endswith("_test.py")
            or path.name in PROTECTED_NAMES or path.name == "test.py")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--instances", type=Path, required=True)
    parser.add_argument("--repos", type=Path, required=True, help="clean clones, one directory per repo name")
    parser.add_argument("--venvs", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--python", default=sys.executable)
    parser.add_argument("--plugin", type=Path, required=True, help="path to pytest_outcomes.py")
    parser.add_argument("--workers", type=int, default=6)
    parser.add_argument("--timeout", type=int, default=300)
    parser.add_argument("--extras", type=Path, help="JSON map: repo name -> extra pip requirements")
    args = parser.parse_args()
    for name in ("instances", "repos", "venvs", "output", "plugin"):
        setattr(args, name, getattr(args, name).resolve())
    instances = [json.loads(line) for line in args.instances.read_text().splitlines() if line.strip()]
    extras = json.loads(args.extras.read_text()) if args.extras else {}
    args.output.mkdir(parents=True, exist_ok=True)
    plugin_dir = args.output / "plugin"
    plugin_dir.mkdir(exist_ok=True)
    shutil.copyfile(args.plugin, plugin_dir / f"{PLUGIN_MODULE}.py")
    repos = sorted({row["repo"] for row in instances})
    envs = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=min(4, len(repos))) as pool:
        futures = {pool.submit(prepare_venv, repo, args.repos / repo, args.venvs / repo, args.python,
                               extras.get(repo, [])): repo for repo in repos}
        for future in concurrent.futures.as_completed(futures):
            repo = futures[future]
            try:
                envs[repo] = future.result()
            except Exception as exc:  # report the environment failure, keep other repos going
                envs[repo] = {"repo": repo, "error": str(exc)[-1500:]}
            print(json.dumps(envs[repo]), flush=True)
    ready = [row for row in instances if "error" not in envs[row["repo"]]]
    started = time.monotonic()
    records = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = [pool.submit(admit, row, args.repos / row["repo"], args.venvs / row["repo"], plugin_dir,
                               args.output, args.timeout) for row in ready]
        for future in concurrent.futures.as_completed(futures):
            try:
                record = future.result()
            except Exception as exc:
                record = {"admitted": False, "reason": f"admission crashed: {type(exc).__name__}: {str(exc)[-800:]}"}
            records.append(record)
            print(json.dumps({k: v for k, v in record.items() if k not in {"task", "tail"}}), flush=True)
    elapsed = time.monotonic() - started
    admitted = sorted((r["task"] for r in records if r["admitted"]), key=lambda task: task["id"])
    for split in ("train", "eval"):
        rows = [task for task in admitted if task["split"] == split]
        (args.output / f"{split}.jsonl").write_text("".join(json.dumps(task) + "\n" for task in rows))
    summary = {"instances": len(instances), "repos": envs, "admitted": len(admitted),
               "by_split": {s: sum(t["split"] == s for t in admitted) for s in ("train", "eval")},
               "by_repo": {repo: {"selected": sum(r["repo"] == repo for r in instances),
                                  "admitted": sum(t["metadata"]["source_repo"] == repo for t in admitted)}
                           for repo in repos},
               "rejections": {}, "admission_seconds": round(elapsed, 1),
               "admission_throughput_per_min": round(len(records) / elapsed * 60, 2) if elapsed else None}
    for record in records:
        if not record["admitted"]:
            reason = record.get("reason", "unknown")
            summary["rejections"][reason] = summary["rejections"].get(reason, 0) + 1
    (args.output / "admission.jsonl").write_text("".join(
        json.dumps({k: v for k, v in r.items() if k != "task"}) + "\n" for r in records))
    (args.output / "summary.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps({k: summary[k] for k in ("instances", "admitted", "by_split", "rejections",
                                              "admission_seconds", "admission_throughput_per_min")}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
